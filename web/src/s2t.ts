// Sort phrase keys by length descending to match longest phrases first
const SORTED_PHRASES = Object.keys(PHRASE_MAP).sort((a, b) => b.length - a.length);

export function toTraditionalChinese(text: string): string {
  if (!text) return text;
  let result = text;
  for (const phrase of SORTED_PHRASES) {
    if (result.includes(phrase)) {
      result = result.replaceAll(phrase, PHRASE_MAP[phrase]);
    }
  }
  let converted = "";
  for (let i = 0; i < result.length; i++) {
    const char = result[i];
    converted += CHAR_MAP.get(char) ?? char;
  }
  return converted;
}
